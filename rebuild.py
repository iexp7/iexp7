def update_profile(root):
    namespace = "{http://www.w3.org/2000/svg}"
    for text_elem in root.iter():
        if text_elem.text:
            for old_text, new_text in PROFILE_REPLACEMENTS.items():
                text_elem.text = text_elem.text.replace(old_text, new_text)
        if text_elem.tail:
            for old_text, new_text in PROFILE_REPLACEMENTS.items():
                text_elem.tail = text_elem.tail.replace(old_text, new_text)

    for text_elem in root.iter(namespace + "text"):
        children = list(text_elem)
        for index, child in enumerate(children[:-1]):
            if child.get("class") != "key":
                continue

            old_key = child.text
            new_key = {"keralacoderscafe.in": "Rajasthancoderscafe.in", "B.A": "B.CA"}.get(old_key)
            if new_key is None:
                continue

            child.text = new_key
            gap = children[index + 1]
            if gap.get("class") == "cc" and gap.text:
                dot_change = len(new_key) - len(old_key)
                dot_count = gap.text.count(".")
                gap.text = gap.text.replace("." * dot_count, "." * (dot_count - dot_change), 1)

    for element in root.iter():
        if element.get("id") == "repo_data":
            element.text = "10"
        elif element.get("id") == "follower_data":
            element.text = "0"

def rebuild_svg(filename, url):
    # 1. Download original SVG
    urllib.request.urlretrieve(url, filename)
    
    ET.register_namespace('', 'http://www.w3.org/2000/svg')
    tree = ET.parse(filename)
    root = tree.getroot()
    update_profile(root)
    
    # 2. Update width to 1400px, height to 650px
    if 'width' in root.attrib:
        root.attrib['width'] = "1400px"
    if 'height' in root.attrib:
        root.attrib['height'] = "650px"
        
    for rect in root.findall('.//{http://www.w3.org/2000/svg}rect'):
        rect.attrib['width'] = "1400px"
        rect.attrib['height'] = "650px"
        
    # 3. Inject ASCII art at x=15 and font-size 9px
    for text_elem in root.findall('.//{http://www.w3.org/2000/svg}text'):
        if text_elem.get('class') == 'ascii':
            # Clear old tspans
            for child in list(text_elem):
                text_elem.remove(child)
                
            text_elem.set('font-size', '9px')
            
            lines = ascii_art.split('\n')
            y_offset = 52
            for line in lines:
                tspan = ET.SubElement(text_elem, '{http://www.w3.org/2000/svg}tspan')
                tspan.set('x', '15')
                tspan.set('y', str(y_offset))
                tspan.text = line
                y_offset += 11
            
            continue
            
        # 4. Shift stats text (and all its tspans) from x=390 to x=580
        if text_elem.get('x') == '390':
            text_elem.set('x', '580')
            for tspan in text_elem.findall('.//{http://www.w3.org/2000/svg}tspan'):
                if tspan.get('x') == '390':
                    tspan.set('x', '580')

    tree.write(filename, encoding="utf-8", xml_declaration=True)

